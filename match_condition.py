

num = 6

match num:
    case 0:
        print("The number is zero.")
    case 1:
        print("The number is one.")
    case 2:
        print("The number is two.")
    case 3:
        print("The number is three.")
    case 4:
        print("The number is four.")
    case 5:
        print("The number is five.")
    case _:
        print("You entered an invalid number.")